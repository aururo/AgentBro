// Perf artifact layout (spec C3). Pure path maths: no I/O, so the containment
// rules can be asserted without a filesystem.
//
// Everything perf-related lives under `.llm-wiki/perf/<site>/`, deliberately
// outside the library folder: HAR files carry credentials and the library is a
// place people share, export and search.
import { isWithin } from '../contract.js'

export const PERF_ROOT = 'perf'

/** `<root>/.llm-wiki` */
export function dataDir(root) {
  return `${trim(root)}/.llm-wiki`
}

/** `<root>/.llm-wiki/perf/<siteId>` */
export function sitePerfDir(root, siteId) {
  const id = String(siteId ?? '').trim()
  if (id === '' || /[/\\]/.test(id) || id === '.' || id === '..') throw new Error(`unsafe site id: ${siteId}`)
  return `${dataDir(root)}/${PERF_ROOT}/${id}`
}

/** `<...>/record/<recId>` */
export function recordDir(root, siteId, recId) {
  return `${sitePerfDir(root, siteId)}/record/${safeId(recId)}`
}

/** `<...>/run/<runId>` — used from P4 onward, defined here so the layout is one place. */
export function runDir(root, siteId, runId) {
  return `${sitePerfDir(root, siteId)}/run/${safeId(runId)}`
}

/** `<...>/script/<sceneSlug>` — the current-script pointer lives here (spec C10.8). */
export function scriptDir(root, siteId, sceneSlug) {
  return `${sitePerfDir(root, siteId)}/script/${safeId(sceneSlug)}`
}

/**
 * Reject ids that could escape their directory. Rec ids are generated by us, but
 * this is also called with values echoed back from the panel.
 * @param {string} value
 */
export function safeId(value) {
  const text = String(value ?? '').trim()
  if (text === '' || text === '.' || text === '..') throw new Error(`unsafe id: ${value}`)
  if (/[/\\\0]/.test(text)) throw new Error(`unsafe id: ${value}`)
  return text
}

/**
 * Lexical containment check for a path under the perf data dir. Disk writers must
 * still rely on the directory they created rather than on this alone; it exists
 * to reject crafted ids before any `mkdir`.
 * @param {string} root
 * @param {string} candidate
 */
export function isInsidePerf(root, candidate) {
  return isWithin(dataDir(root), candidate, { allowSelf: false })
}

/** `rec_20261108T2150_ab12` */
export function newRecordId(now = new Date(), random = Math.random) {
  const pad = (n) => String(n).padStart(2, '0')
  const stamp = `${now.getFullYear()}${pad(now.getMonth() + 1)}${pad(now.getDate())}T${pad(now.getHours())}${pad(now.getMinutes())}${pad(now.getSeconds())}`
  const suffix = Math.floor(random() * 0xffff).toString(16).padStart(4, '0').slice(-4)
  return `rec_${stamp}_${suffix}`
}

/** `r_20261108T2210_3f9a` — kept here so run ids and record ids share one shape. */
export function newRunId(now = new Date(), random = Math.random) {
  return newRecordId(now, random).replace(/^rec_/, 'r_')
}

function trim(value) {
  return String(value ?? '').replace(/[\\/]+$/, '')
}
