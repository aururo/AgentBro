/**
 * Build a translator. Missing keys return the key itself so a gap shows up in
 * the UI during review instead of silently rendering an empty string.
 * @param {boolean} isEnglish
 */
export function createTranslator(isEnglish) {
  const dict = isEnglish ? en : zh
  // `{name}` parameters, because a message that has to name the session cannot be
  // assembled from fragments without producing half-translated sentences.
  return (key, params) => {
    const text = dict[key] ?? key
    if (params === undefined) return text
    return text.replace(/\{(\w+)\}/g, (whole, name) => (name in params ? String(params[name]) : whole))
  }
}

// --- host language -----------------------------------------------------------
//
// The host's locale service can only be read through `ctx.reflect.get(name,
// false)` from inside `apply`. Reading it off the component's props
// (`props.service.ctx.locale`) is an *undeclared* inject access: Cordis throws,
// and any try/catch around it silently pins the panel to Chinese forever. So the
// service is parked here once, during `apply`, and everything else asks this
// module instead of reaching into the context.

/** @type {any} */
let hostLocale = null

/** Called once from `apply`. Pass null when the optional service is absent. */
export function setHostLocale(service) {
  hostLocale = service ?? null
}

/**
 * True when the host is running in English. Tolerates both shapes the service
 * might have (`getSnapshot().active` or a plain `active` field) and never throws:
 * the panel's own language is a preference, not a correctness requirement.
 */
export function hostIsEnglish() {
  try {
    const snapshot = typeof hostLocale?.getSnapshot === 'function' ? hostLocale.getSnapshot() : hostLocale
    return snapshot?.active === 'en'
  } catch {
    return false
  }
}
